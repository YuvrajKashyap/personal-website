// Builds the site's web fonts from the originals in assets/fonts.
//
// Every family keeps exactly the faces Google Fonts serves (same files, same
// unicode-range, same fallback metrics). The one change is the Latin face, the
// one every visitor downloads: it is split in two.
//
//   core  the characters the site can actually show (all printable ASCII, the
//         typographic marks below, and every character found in src/), cut
//         from the original file with all OpenType features and variable
//         axes kept. This is the file that gets preloaded.
//   rest  the untouched original Latin file, limited to every Latin character
//         the core leaves out. Browsers only fetch it if a page shows one.
//
// So new copy can never fall back to another font: a character the core lacks
// comes from the original file. The script runs before every dev and build, so
// the core always matches the current copy.
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const sourceDir = path.join(root, "assets/fonts/source");
const outDir = path.join(root, "public/fonts");
const cssOut = path.join(root, "src/app/fonts.generated.css");
const preloadOut = path.join(root, "src/app/font-preloads.generated.ts");
const families = JSON.parse(fs.readFileSync(path.join(root, "assets/fonts/fonts.json"), "utf8"));

// Always in the core: anything a visitor might type into a form, plus the
// common typographic marks, whether or not today's copy uses them.
const ALWAYS = [
  ...Array.from({ length: 0x7e - 0x20 + 1 }, (_, i) => 0x20 + i),
  ...[..." ‘’‚“”„–—…•·′″©®™°×÷±€£¥¢§¶†‡«»¿¡"].map((c) => c.codePointAt(0)),
];

function scanSourceCharacters(dir, found) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) scanSourceCharacters(full, found);
    else if (/\.(tsx?|jsx?|mjs|css|json|mdx?|txt)$/.test(entry.name) && !entry.name.includes(".generated.")) {
      const text = fs.readFileSync(full, "utf8");
      for (const ch of text) found.add(ch.codePointAt(0));
      // Characters written as escapes: JS "—" or "\u{2014}", CSS
      // content: "\2023", and HTML entities like &#8599; or &#x2197;.
      for (const m of text.matchAll(/\\u\{([0-9a-f]{1,6})\}|\\u([0-9a-f]{4})|\\([0-9a-f]{2,6})(?![0-9a-z])|&#x([0-9a-f]+);/gi)) {
        found.add(parseInt(m[1] ?? m[2] ?? m[3] ?? m[4], 16));
      }
      for (const m of text.matchAll(/&#(\d+);/g)) found.add(Number(m[1]));
    }
  }
  return found;
}

function parseRange(text) {
  const points = new Set();
  for (const part of text.split(",")) {
    const token = part.trim().replace(/^U\+/i, "");
    if (token.includes("?")) {
      const lo = parseInt(token.replace(/\?/g, "0"), 16);
      const hi = parseInt(token.replace(/\?/g, "F"), 16);
      for (let c = lo; c <= hi; c++) points.add(c);
    } else {
      const [lo, hi = lo] = token.split("-").map((h) => parseInt(h, 16));
      for (let c = lo; c <= hi; c++) points.add(c);
    }
  }
  return points;
}

function formatRange(points) {
  const sorted = [...points].sort((a, b) => a - b);
  const parts = [];
  for (let i = 0; i < sorted.length; i++) {
    let j = i;
    while (j + 1 < sorted.length && sorted[j + 1] === sorted[j] + 1) j++;
    const hex = (c) => c.toString(16).toUpperCase();
    parts.push(i === j ? `U+${hex(sorted[i])}` : `U+${hex(sorted[i])}-${hex(sorted[j])}`);
    i = j;
  }
  return parts.join(",");
}

function emit(buffer, baseName) {
  const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 10);
  const name = `${baseName}.${hash}.woff2`;
  fs.writeFileSync(path.join(outDir, name), buffer);
  return `/fonts/${name}`;
}

const wanted = scanSourceCharacters(path.join(root, "src"), new Set(ALWAYS));

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const css = [
  "/* Generated by scripts/fonts/build-fonts.mjs. Do not edit by hand. */",
];
const rootVars = [];
const preloads = [];
const report = [];

for (const family of families) {
  for (const face of family.faces) {
    const source = fs.readFileSync(path.join(sourceDir, face.file));
    const baseName = face.file.replace(/\.woff2$/, "");
    const descriptors = `font-family:"${family.family}";font-style:${face.style};font-weight:${face.weight};font-display:swap`;
    const original = emit(source, baseName);

    if (!face.preloaded) {
      css.push(`@font-face{${descriptors};src:url(${original}) format("woff2");unicode-range:${face.unicodeRange}}`);
      continue;
    }

    const latin = parseRange(face.unicodeRange);
    const core = new Set([...latin].filter((c) => wanted.has(c)));
    const rest = new Set([...latin].filter((c) => !core.has(c)));
    const coreBuffer = await subsetFont(source, String.fromCodePoint(...core), { targetFormat: "woff2" });
    const coreUrl = emit(coreBuffer, `${baseName}-core`);
    preloads.push(coreUrl);
    report.push(`${family.family} ${face.weight}: ${source.length} -> ${coreBuffer.length} bytes (${core.size} of ${latin.size} characters)`);

    css.push(`@font-face{${descriptors};src:url(${original}) format("woff2");unicode-range:${formatRange(rest)}}`);
    css.push(`@font-face{${descriptors};src:url(${coreUrl}) format("woff2");unicode-range:${formatRange(core)}}`);
  }
  css.push(`@font-face{font-family:"${family.family} Fallback";${family.fallback}}`);
  rootVars.push(`${family.cssVar}:${family.value}`);
}

css.push(`:root{${rootVars.join(";")}}`);
fs.writeFileSync(cssOut, css.join("\n") + "\n");
fs.writeFileSync(
  preloadOut,
  "// Generated by scripts/fonts/build-fonts.mjs. Do not edit by hand.\n" +
    `export const FONT_PRELOADS = ${JSON.stringify(preloads, null, 2)} as const;\n`,
);
console.log(report.join("\n"));
